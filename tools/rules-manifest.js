'use strict';
// Rules version lock (server/docs/auth-lobby-protocol.md 2.7): writes rules-manifest.json and options/rulesVersion.js,
// or checks them. Run it before packaging a release, after any change to a rules script:
//   node tools/rules-manifest.js [--list ../diplomacy_server/server/gameScriptList.js] [--check]
// The script list is the server's rules script list (server/gameScriptList.js in diplomacy_server, in order); without
// that checkout, the paths already in rules-manifest.json. rulesVersion = sha256 over, per script, its path, a NUL, its
// file bytes, a NUL. Prints `rulesVersion <hex>`; --check writes nothing and exits 1 when a generated file is stale.
// diplomacy_server's server/tools/rules-manifest.js writes byte-identical files.
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const MANIFEST_FILE = 'rules-manifest.json';
const CLIENT_VERSION_FILE = 'options/rulesVersion.js';
const DEFAULT_LIST = path.join(ROOT, '../diplomacy_server/server/gameScriptList.js');

function scriptList(listFile) {
    if (fs.existsSync(listFile)) return require(listFile).scriptOrder;
    return JSON.parse(fs.readFileSync(path.join(ROOT, MANIFEST_FILE), 'utf8')).scripts.map(script => script.path);
}

function computeRulesVersion(scriptOrder) {
    const hash = crypto.createHash('sha256');
    const scripts = scriptOrder.map(file => {
        const data = fs.readFileSync(path.join(ROOT, file));
        hash.update(file).update('\0').update(data).update('\0');
        return {path: file, sha256: crypto.createHash('sha256').update(data).digest('hex'), bytes: data.length};
    });
    return {rulesVersion: hash.digest('hex'), scripts};
}

function manifestFiles({rulesVersion, scripts}) {
    const manifest = JSON.stringify({format: 1, algorithm: 'sha256(path NUL bytes NUL ...)', rulesVersion, scripts}, null, 2) + '\n';
    const clientScript = '// Generated by tools/rules-manifest.js from the rules script list (rules-manifest.json): do not edit.\n' +
        '// Sent as rulesVersion in auth:google, auth:session and game:open (server/docs/auth-lobby-protocol.md 2.7).\n' +
        `const RULES_VERSION = '${rulesVersion}'\n`;
    return {[MANIFEST_FILE]: manifest, [CLIENT_VERSION_FILE]: clientScript};
}

function main(argv) {
    let listFile = DEFAULT_LIST, check = false;
    for (let i = 0; i < argv.length; ++i) {
        if (argv[i] === '--check') check = true;
        else if (argv[i] === '--list' && i + 1 < argv.length) listFile = path.resolve(argv[++i]);
        else throw new Error(`unexpected argument ${argv[i]}`);
    }
    const computed = computeRulesVersion(scriptList(listFile));
    console.log(`rulesVersion ${computed.rulesVersion}`);
    let stale = 0;
    for (const [file, text] of Object.entries(manifestFiles(computed))) {
        const target = path.join(ROOT, file);
        const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
        if (current === text) continue;
        stale++;
        if (check) console.error(`stale ${file}`);
        else {
            fs.writeFileSync(target, text);
            console.log(`wrote ${file}`);
        }
    }
    return check && stale ? 1 : 0;
}

process.exitCode = main(process.argv.slice(2));
